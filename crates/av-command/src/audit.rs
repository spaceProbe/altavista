    #[test]
    fn format_line_includes_decision_id_and_policy_hash_only_when_present() {
        let command = command("cmd-3", "sat-1", "mode");
        let transition = transition(CommandState::Checked, 0, "policy", "decision_id=abc policy_hash=def allow=true", "");
        let decision = PolicyDecision { decision_id: "abc".to_string(), allow: true, policy_hash: "def".to_string(), reasons: vec![], matched_rule_path: "data.altavista.authority.allow".to_string(), evaluated_tai_ns: 0, input: None };
        let with_decision = format_line(&event_for_transition(&command, &transition, Some(&decision)));
        assert!(with_decision.contains("decisionId=\"abc\""), "{with_decision}");
        assert!(with_decision.contains("policyHash=\"def\""), "{with_decision}");

        let without_decision = format_line(&event_for_transition(&command, &transition, None));
        assert!(!without_decision.contains("decisionId="), "{without_decision}");
        assert!(!without_decision.contains("policyHash="), "{without_decision}");
    }

    fn tmp_path(name: &str) -> PathBuf {
        std::env::temp_dir().join(format!("av-command-audit-test-{name}-{}.log", std::process::id()))
    }

    #[test]
    fn audit_writer_appends_the_exact_line_plus_one_newline_to_the_configured_file() {
        let path = tmp_path("write-exact");
        let _ = std::fs::remove_file(&path);
        let writer = AuditWriter::open(&AuditSinkConfig::File(path.clone())).unwrap();

        let command = command("cmd-1", "sat-1", "mode");
        let transition = transition(CommandState::Proposed, 0, "model-x", "proposed via CommandAuthorityService.Propose", "");
        writer.write(&event_for_transition(&command, &transition, None)).unwrap();

        let contents = std::fs::read_to_string(&path).unwrap();
        assert_eq!(contents, format!("{}\n", format_line(&event_for_transition(&command, &transition, None))));

        let _ = std::fs::remove_file(&path);
    }

    #[test]
    fn audit_writer_appends_across_multiple_writes_without_truncating() {
        let path = tmp_path("append");
        let _ = std::fs::remove_file(&path);
        let writer = AuditWriter::open(&AuditSinkConfig::File(path.clone())).unwrap();

        let command = command("cmd-1", "sat-1", "mode");
        for (state, tai_ns) in [(CommandState::Proposed, 0), (CommandState::Checked, 1)] {
            let transition = transition(state, tai_ns, "p", "r", "");
            writer.write(&event_for_transition(&command, &transition, None)).unwrap();
        }

        let contents = std::fs::read_to_string(&path).unwrap();
        assert_eq!(contents.lines().count(), 2);

        let _ = std::fs::remove_file(&path);
    }

    /// **When no `[audit]` sink is configured**: `write` is a no-op returning `Ok(())`, and no
    /// file is ever created.
    #[test]
    fn a_disabled_sink_is_a_no_op_that_creates_no_file() {
        let path = tmp_path("disabled");
        let _ = std::fs::remove_file(&path);
        let writer = AuditWriter::open(&AuditSinkConfig::Disabled).unwrap();

        let command = command("cmd-1", "sat-1", "mode");
        let transition = transition(CommandState::Proposed, 0, "p", "r", "");
        writer.write(&event_for_transition(&command, &transition, None)).expect("a disabled sink's write must still return Ok");

        assert!(!path.exists(), "a disabled sink must create no file at all");
    }

