const RUN_ID: &str = "run-command-trail";
const FIXTURE_RUN_ID: &str = "demo-command-trail-frozen";

fn fixture_bytes() -> Vec<u8> {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/fixtures/demo_command_trail.runproducts.bin");
    std::fs::read(&path).unwrap_or_else(|e| panic!("read real RunProducts fixture at {}: {e}", path.display()))
}

fn catalogue_and_ladder(marking: &str) -> (BTreeMap<String, CatalogueEntry>, ClearanceLadder) {
    let mut entries = BTreeMap::new();
    entries.insert(RUN_ID.to_string(), CatalogueEntry::from_raw_bytes(Label { marking: marking.to_string(), caveats: vec![] }, fixture_bytes()));
    let ladder = ClearanceLadder::new(vec!["UNCLASSIFIED".to_string(), "CUI".to_string(), "SECRET".to_string()]);
    (entries, ladder)
}

fn events_request(clearance: &str) -> GatewayQueryRequest {
    GatewayQueryRequest {
        run: Some(RunIdentity { run_id: RUN_ID.to_string(), config_hash: String::new() }),
        caller_clearance: clearance.to_string(),
        selector: GatewaySelector::Events as i32,
        caller_supplied_products_uri: String::new(),
    }
}

/// Sanity: the fixture really is what its own generator (`crates/av-run/tests/
/// command_dispatch_e2e.rs::generate_command_trail_run_products_fixture`) documents -- decoded
/// directly (not through the gateway) so a wrong or stale committed fixture would fail here
/// before this file's own gateway assertions could be blamed for it.
#[test]
fn the_fixture_is_the_real_command_trail_run_and_carries_the_expected_transitions() {
    let rp = av_cdm::pb::RunProducts::decode(fixture_bytes().as_slice()).expect("fixture decodes as RunProducts");
    assert_eq!(rp.run_id, FIXTURE_RUN_ID);
    assert!(!rp.trajectories.is_empty());
    assert!(!rp.events.is_empty());

    let transitions: Vec<_> = rp.events.iter().filter(|e| e.kind == EventKind::CommandTransition as i32 && e.reference_id == "safe1").collect();
    let states: Vec<&str> = transitions.iter().map(|e| e.name.as_str()).collect();
    assert_eq!(states, vec!["COMMAND_STATE_PROPOSED", "COMMAND_STATE_CHECKED", "COMMAND_STATE_AUTHORIZED", "COMMAND_STATE_DISPATCHED", "COMMAND_STATE_ACKED"], "{transitions:#?}");
    let epochs: Vec<i64> = transitions.iter().map(|e| e.tai_ns).collect();
    assert_eq!(epochs, vec![1_767_225_637_000_000_000, 1_767_225_637_000_000_001, 1_767_225_637_000_000_002, 1_767_225_647_000_000_000, 1_767_225_648_400_000_000], "the fixture's own real, measured epochs (see this file's own module doc's generator output) -- a fixture regenerated from a changed setup would disagree here, loudly");
}

/// The command-trail fixture, served through a REAL `DataGatewayService` over a real loopback
/// socket: `GATEWAY_SELECTOR_EVENTS` returns the identical five-transition command trail for
/// `"safe1"`, in the gateway's own documented sorted order (`crate::drm::events::
/// epoch_id_order`'s `(tai_ns, id)` -- `crates/av-kernel/src/drm/events.rs`'s own doc comment;
/// the gateway itself never re-sorts, it returns `RunProducts.events` exactly as the real
/// kernel run wrote them, already in that order).
#[tokio::test]
async fn the_gateway_serves_the_real_command_trail_over_a_real_socket_in_sorted_order() {
    let (entries, ladder) = catalogue_and_ladder("CUI");
    let mut harness = GatewayServerHarness::spawn(entries, ladder).await;

    let resp = harness.client.query(events_request("CUI")).await.expect("EVENTS query over the real command-trail fixture").into_inner();
    assert!(!resp.events.is_empty());

    // Sorted order, over the WHOLE response (not just the filtered subset below) -- proves the
    // gateway is not merely returning a coincidentally-sorted five-element slice.
    let mut prev: Option<(i64, &str)> = None;
    for e in &resp.events {
        let key = (e.tai_ns, e.id.as_str());
        if let Some(p) = prev {
            assert!(p <= key, "events must be non-decreasing in (tai_ns, id) order; {p:?} came before {key:?}");
        }
        prev = Some(key);
    }

    // The specific command trail this fixture actually contains: name the states and the
    // command id, never merely "at least one event" (this task's own instruction).
    let transitions: Vec<_> = resp.events.iter().filter(|e| e.kind == EventKind::CommandTransition as i32 && e.reference_id == "safe1").collect();
    let states: Vec<&str> = transitions.iter().map(|e| e.name.as_str()).collect();
    assert_eq!(states, vec!["COMMAND_STATE_PROPOSED", "COMMAND_STATE_CHECKED", "COMMAND_STATE_AUTHORIZED", "COMMAND_STATE_DISPATCHED", "COMMAND_STATE_ACKED"], "{transitions:#?}");
    assert_eq!(transitions[0].tai_ns, 1_767_225_637_000_000_000, "PROPOSED");
    assert_eq!(transitions[1].tai_ns, 1_767_225_637_000_000_001, "CHECKED");
    assert_eq!(transitions[2].tai_ns, 1_767_225_637_000_000_002, "AUTHORIZED");
    assert_eq!(transitions[3].tai_ns, 1_767_225_647_000_000_000, "DISPATCHED");
    assert_eq!(transitions[4].tai_ns, 1_767_225_648_400_000_000, "ACKED");
    for t in &transitions {
        assert_eq!(t.entity_id, "controller", "the demo attitude DRM's own mode-command target");
    }

    assert_eq!(harness.counters.get("gateway_product_missing_on_host"), 0, "a genuinely EVENTS-populated fixture must never be refused as missing on this host");
    harness.shutdown().await;
}

/// D2's label enforcement applies to this fixture exactly like any other real fixture
/// (`crates/av-gateway/tests/real_run_products.rs`'s own module doc line: "the same real
/// fixture" -- the point of this whole task is that the command-trail fixture is not a special
/// case): a caller below the fixture's own CUI label is refused `PERMISSION_DENIED` over the
/// real gRPC surface, and the refusal is counted.
#[tokio::test]
async fn a_caller_below_the_fixtures_own_clearance_is_refused_over_the_real_socket_and_counted() {
    let (entries, ladder) = catalogue_and_ladder("CUI");
    let mut harness = GatewayServerHarness::spawn(entries, ladder).await;

    let err = harness.client.query(events_request("UNCLASSIFIED")).await.expect_err("a caller below the fixture's own CUI label must be refused");
    assert_eq!(err.code(), Code::PermissionDenied, "{err:?}");
    assert_eq!(harness.counters.get("label_over_clearance"), 1, "the refusal must be counted (ADR-004: everything rejected is counted)");

    // The identical query, at the fixture's own clearance, still succeeds against this same
    // running server -- proves the refusal above was genuinely about the caller's clearance,
    // not a broken server or a malformed request this fixture happens to trigger.
    let ok = harness.client.query(events_request("CUI")).await.expect("the identical query at the fixture's own clearance must succeed");
    assert!(!ok.into_inner().events.is_empty());

    harness.shutdown().await;
}
