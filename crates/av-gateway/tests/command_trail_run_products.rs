//! R3.4 (`docs/open-questions.md` question 206, `docs/aiplane-plan.md`'s round-2 declared gap):
//! the gateway proven against the A3.3 command-trail replay fixture's own kind of run
//! products -- a REAL, git-tracked `RunProducts` (`tests/fixtures/demo_command_trail.
//! runproducts.bin`) whose `events` genuinely include `EVENT_KIND_COMMAND_TRANSITION` events
//! for a command that actually went through the real `CommandAuthorityService` and the real
//! kernel, served through a REAL `DataGatewayService` over a real loopback socket (this file's
//! own `harness` module, below).
//!
//! ## What this fixture proves that `demo_measurements.runproducts.bin` could not
//!
//! `crates/av-gateway/tests/real_run_products.rs`'s own fixture
//! (`demo_measurements.runproducts.bin`) is a real `execute()` run with real trajectories,
//! events, and measurements -- but its own `events` carry no `EVENT_KIND_COMMAND_TRANSITION`
//! at all (that file's own module doc, and `docs/aiplane-plan.md`'s round-2 declared gap,
//! state this plainly: "the gateway is not yet proven against a run whose events include a
//! command trail"). This file closes that gap: `GATEWAY_SELECTOR_EVENTS` against THIS fixture
//! returns a real, five-transition command trail (`PROPOSED` -> `CHECKED` -> `AUTHORIZED` ->
//! `DISPATCHED` -> `ACKED`) for a real command id (`"safe1"`) that a real
//! `CommandAuthorityServiceImpl` and a real `av_kernel::drm::execute` run actually produced --
//! never a hand-built `Event` literal.
//!
//! ## How the fixture was produced (reproducible recipe)
//!
//! `tests/fixtures/demo_command_trail.runproducts.bin` is generated by `crates/av-run/tests/
//! command_dispatch_e2e.rs::generate_command_trail_run_products_fixture` (`#[ignore]`d) --
//! see that test's own module doc for the exact recipe (a real `CommandAuthorityService` over
//! a real loopback socket dispatches the demo attitude DRM's `"safe1"` SAFE-mode command
//! through `av_run::command_adapter::KernelCommandAdapter` into a live `av_kernel::drm::execute`
//! run of `drms/demo_attitude_command.{drm,sos}.yaml`, under the frozen `run_id`
//! `"demo-command-trail-frozen"`). Regenerate with:
//! ```text
//! export PATH="/opt/homebrew/opt/rustup/bin:$PATH"
//! export GMAT_ROOT="/Users/probe/code/AltaVista/GMAT R2026a"
//! export CFS_MIRROR_DIR=/Users/probe/code/AltaVista/third_party/mirrors
//! cargo test -p av-run --test command_dispatch_e2e -- --ignored --nocapture generate_command_trail_run_products_fixture
//! ```
//!
//! ## Why a local, single-use harness (`mod harness`), not `tests/common/mod.rs`
//!
//! `crates/av-gateway/tests/common/mod.rs`'s own module doc states its own convention plainly:
//! a helper used by only one test binary in this crate lives in that binary directly (its own
//! example, `tests/propose_only.rs`'s `CommandAuthorityHarness`); one used by several lives in
//! `common`. No other test binary in this crate needs a bare `DataGatewayService`-only server
//! (this fixture carries no command proposal to authorize, so `ModelProposeService`/
//! `CommandAuthorityService` are not wired here at all -- this is the read path alone), so this
//! file's own harness stays local, mirroring `tests/propose_only.rs`'s identical pattern.

mod harness {
    use std::collections::BTreeMap;
    use std::sync::Arc;

    use av_gateway::catalogue::{CatalogueEntry, RunCatalogue};
    use av_gateway::counters::Counters;
    use av_gateway::gateway::{DataGatewayServiceImpl, DataGatewayServiceServer, GatewayCore};
    use av_gateway::labels::ClearanceLadder;
    use av_gateway::pb::data_gateway_service_client::DataGatewayServiceClient;
    use tokio::net::TcpListener;
    use tokio::sync::oneshot;
    use tokio_stream::wrappers::TcpListenerStream;
    use tonic::transport::{Channel, Endpoint, Server};

    /// A REAL `DataGatewayService` (`crate::harness`'s own name for [`av_gateway::gateway::
    /// DataGatewayServiceImpl`]) over a real loopback socket -- never `GatewayCore::query`
    /// called in-process, so this test genuinely exercises the gRPC wire adapter
    /// (`to_status`'s own `RefusalReason` -> `tonic::Status` mapping included), not only the
    /// core resolution logic `crates/av-gateway/tests/real_run_products.rs` already covers
    /// in-process.
    pub struct GatewayServerHarness {
        pub client: DataGatewayServiceClient<Channel>,
        pub counters: Arc<Counters>,
        shutdown_tx: Option<oneshot::Sender<()>>,
        handle: Option<tokio::task::JoinHandle<()>>,
    }

    impl GatewayServerHarness {
        pub async fn spawn(entries: BTreeMap<String, CatalogueEntry>, ladder: ClearanceLadder) -> Self {
            let counters = Arc::new(Counters::new());
            let core = Arc::new(GatewayCore::new(RunCatalogue::new(entries), ladder, counters.clone()));

            let listener = TcpListener::bind("127.0.0.1:0").await.expect("bind an ephemeral loopback port");
            let addr = listener.local_addr().expect("local_addr");
            let incoming = TcpListenerStream::new(listener);

            let (shutdown_tx, shutdown_rx) = oneshot::channel::<()>();
            let handle = tokio::spawn(async move {
                Server::builder()
                    .add_service(DataGatewayServiceServer::new(DataGatewayServiceImpl::new(core)))
                    .serve_with_incoming_shutdown(incoming, async {
                        let _ = shutdown_rx.await;
                    })
                    .await
                    .expect("server exits cleanly");
            });

            let channel = Endpoint::from_shared(format!("http://{addr}"))
                .expect("valid endpoint URI")
                .connect()
                .await
                .expect("connect to the just-spawned DataGatewayService over its real loopback socket");
            let client = DataGatewayServiceClient::new(channel);

            Self { client, counters, shutdown_tx: Some(shutdown_tx), handle: Some(handle) }
        }

        pub async fn shutdown(mut self) {
            if let Some(tx) = self.shutdown_tx.take() {
                let _ = tx.send(());
            }
            if let Some(handle) = self.handle.take() {
                let _ = handle.await;
            }
        }
    }
}

use std::collections::BTreeMap;

use av_cdm::pb::{EventKind, GatewayQueryRequest, GatewaySelector, Label, RunIdentity};
use av_gateway::catalogue::CatalogueEntry;
