"""services/clickhouse/extract_image_packages.py -- writes services/clickhouse/IMAGE_PACKAGES.txt,
the committed package inventory `scripts/kit/sbom.py` reads for the `clickhouse-image` SBOM.

The image is a third-party image we did not build, so there is no build context to enumerate.
What can be read from it, without any network fetch, is its dpkg status file. Take it from the
pinned image (by the digest in IMAGE_DIGEST.md; run under the docker lock wrapper):

    docker run --rm --entrypoint cat clickhouse/clickhouse-server@sha256:<digest> \\
        /var/lib/dpkg/status > <scratch>/dpkg-status.txt
    .venv/bin/python services/clickhouse/extract_image_packages.py \\
        --status <scratch>/dpkg-status.txt \\
        --image clickhouse/clickhouse-server@sha256:<digest> \\
        --os "Ubuntu 22.04.5 LTS (Jammy Jellyfish)" \\
        --out services/clickhouse/IMAGE_PACKAGES.txt

Stdlib only. Output is deterministic (sorted by package name, no timestamps), so re-running it on
the same image reproduces the committed file byte for byte.
"""
from __future__ import annotations

import argparse
from pathlib import Path


def installed_packages(status_text: str) -> list[tuple[str, str, str]]:
    """`(name, version, architecture)` for every dpkg stanza whose Status ends in `installed`,
    sorted by name then version."""
    packages: list[tuple[str, str, str]] = []
    for stanza in status_text.split("\n\n"):
        fields: dict[str, str] = {}
        for line in stanza.splitlines():
            if not line or line[0] in " \t" or ":" not in line:
                continue  # blank line, or a continuation line of a multi-line field
            key, _, value = line.partition(":")
            fields.setdefault(key, value.strip())
        if not fields.get("Package"):
            continue
        if not fields.get("Status", "").endswith(" installed"):
            continue
        packages.append((fields["Package"], fields.get("Version", ""), fields.get("Architecture", "")))
    return sorted(packages)


def render(packages: list[tuple[str, str, str]], image: str, os_name: str) -> str:
    header = [
        "# services/clickhouse/IMAGE_PACKAGES.txt -- the dpkg inventory of the pinned ClickHouse image.",
        "# Generated by services/clickhouse/extract_image_packages.py from `/var/lib/dpkg/status`",
        "# inside the image below; read by scripts/kit/sbom.py for the clickhouse-image SBOM.",
        f"# image: {image}",
        f"# os: {os_name}",
        f"# packages: {len(packages)}",
        "# columns (tab separated): name, version, architecture",
    ]
    return "\n".join(header + ["\t".join(p) for p in packages]) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("--status", required=True, type=Path, help="a copy of the image's /var/lib/dpkg/status")
    parser.add_argument("--image", required=True, help="the registry reference by digest the status came from")
    parser.add_argument("--os", required=True, dest="os_name", help="PRETTY_NAME of the image's /etc/os-release")
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()
    packages = installed_packages(args.status.read_text(encoding="utf-8"))
    args.out.write_text(render(packages, args.image, args.os_name), encoding="utf-8")
    print(f"wrote {args.out}: {len(packages)} packages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
