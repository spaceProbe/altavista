GREP = b"pretend bytes of /bin/grep\n"
LIBC = b"pretend bytes of libc.so.6\n"
PASSWD = b"root:x:0:0:root:/root:/bin/sh\n"
LICENCE_TEXT = b"The Pretend Licence, version 1\n" * 20


def _inventory(image: str, reference: str, digest: str, packages: list[tuple[str, str, list[tuple[str, bytes]]]],
               unowned: list[tuple[str, bytes]]) -> dict:
    return {
        "base_image": {"digest": digest, "image": image, "platform": "linux/arm64", "reference": reference},
        "doc": "docs/kit-operator-supplied.md", "os_release": {"id": "ubuntu", "version_id": "22.04"}, "notes": "", "schema": 1,
        "package_count": len(packages),
        "packages": [
            {"name": n, "version": v, "architecture": "arm64", "source": n, "copyright_file": True, "licences": ["GPL-3+"],
             "machine_readable": True, "files": sorted([p, _sha(b)] for p, b in files)}
            for n, v, files in packages
        ],
        "unowned_files": sorted([p, _sha(b)] for p, b in unowned),
    }


def _fake_index() -> ki.BaseIndex:
    ref = "pretend:1@sha256:" + "ab" * 32
    return ki.BaseIndex({
        "cfs-image": _inventory("cfs-image", ref, "sha256:" + "ab" * 32, [
            ("grep", "3.7-1build1", [("/bin/grep", GREP)]),
            ("libc6", "2.35-0ubuntu3.8", [("/lib/aarch64-linux-gnu/libc.so.6", LIBC)]),
            ("base-files", "12ubuntu4.6", [("/usr/share/common-licenses/Pretend", LICENCE_TEXT)]),
        ], [("/etc/passwd", PASSWD)]),
        "edge-plugin-image": _inventory("edge-plugin-image", "pretend:2@sha256:" + "cd" * 32, "sha256:" + "cd" * 32, [
            ("base-files", "12.4", [("/usr/share/common-licenses/Pretend", LICENCE_TEXT)]),
        ], []),
    })


def _policy(*accepted: ki.AcceptedOverlap) -> ki.OverlapPolicy:
    return ki.OverlapPolicy(excluded_hashes={_sha(b""): "the empty file"}, accepted=tuple(accepted))


def _item(kit_path: str, data: bytes, *, image_path: str | None = None, component: str | None = None, container: str | None = None,
          kind: str = "file") -> ki.KitItem:
    return ki.KitItem(kit_path, kind, _sha(data), len(data), "test", image_path, container, "", component)


def _names(overlaps: list[ki.Overlap]) -> dict[str, set[str]]:
    return {ov.item.kit_path: {b.package for b in ov.base_files} for ov in overlaps}


def test_a_base_package_file_is_found_by_path_and_by_hash_and_names_its_package():
    index, policy = _fake_index(), _policy()
    items = [
        _item("images/cfs-image/rootfs/bin/grep", GREP, image_path="/bin/grep", component="cfs-image"),               # same path, same bytes
        _item("images/cfs-image/rootfs/bin/grep2", b"other bytes", image_path="/bin/grep", component="cfs-image"),     # same path only
        _item("images/cfs-image/rootfs/usr/bin/grep", b"other again", image_path="/usr/bin/grep", component="cfs-image"),   # merged-/usr fold
        _item("packs/data-time/innocent.bin", GREP),                                    # same bytes, unrelated path
        _item("wheels/x.whl!pkg/data.bin", LIBC, container="wheels/x.whl", kind="wheel-member"),   # same bytes, in an archive member
        _item("images/edge-plugin-image/rootfs/etc/passwd", b"mine", image_path="/etc/passwd", component="edge-plugin-image"),   # edge base has no /etc/passwd
        _item("packs/data-time/passwd-copy", PASSWD),                                    # an UNOWNED base file's bytes
        _item("packs/data-time/clean.bin", b"nothing like it"),
    ]
    found = _names(ki.find_overlaps(items, index, policy))
    assert found == {
        "images/cfs-image/rootfs/bin/grep": {"grep"},
        "images/cfs-image/rootfs/bin/grep2": {"grep"},
        "images/cfs-image/rootfs/usr/bin/grep": {"grep"},
        "packs/data-time/innocent.bin": {"grep"},
        "wheels/x.whl!pkg/data.bin": {"libc6"},
        "packs/data-time/passwd-copy": {ki.UNOWNED},
    }


def test_an_application_layer_is_compared_by_path_with_its_own_base_only():
    """The cFS image's Ubuntu base has /bin/grep; a Debian-image layer file at /bin/grep is not at a path
    its own base owns (the same package name in two distributions has the same paths)."""
    index, policy = _fake_index(), _policy()
    other = _item("images/edge-plugin-image/rootfs/bin/grep", b"debian side", image_path="/bin/grep", component="edge-plugin-image")
    assert ki.find_overlaps([other], index, policy) == []
    mine = _item("images/cfs-image/rootfs/bin/grep", b"ubuntu side", image_path="/bin/grep", component="cfs-image")
    assert len(ki.find_overlaps([mine], index, policy)) == 1


def test_empty_content_is_not_compared_by_hash_but_an_empty_file_at_a_base_path_still_fails():
    index = _fake_index()
    index.by_sha[_sha(b"")].append(ki.BaseFile("cfs-image", "grep", "/usr/share/grep/.keep", _sha(b"")))
    policy = _policy()
    elsewhere = _item("packs/data-time/empty", b"")
    assert ki.find_overlaps([elsewhere], index, policy) == []
    index.by_path["/usr/share/grep/.keep"].append(ki.BaseFile("cfs-image", "grep", "/usr/share/grep/.keep", _sha(b"")))
    at_path = _item("images/cfs-image/rootfs/usr/share/grep/.keep", b"", image_path="/usr/share/grep/.keep", component="cfs-image")
    assert [ov.item.kit_path for ov in ki.find_overlaps([at_path], index, policy)] == [at_path.kit_path]


def test_an_accepted_overlap_is_accepted_only_where_and_as_named():
    index = _fake_index()
    both = frozenset({("cfs-image", "base-files", "/usr/share/common-licenses/Pretend"),
                      ("edge-plugin-image", "base-files", "/usr/share/common-licenses/Pretend")})
    anywhere = ki.AcceptedOverlap("any", _sha(LICENCE_TEXT), None, both, "a licence text")
    one_path = ki.AcceptedOverlap("one", _sha(LICENCE_TEXT), frozenset({"packs/data-time/ok.txt"}), both, "a licence text")
    forgot_one = ki.AcceptedOverlap("partial", _sha(LICENCE_TEXT), None, frozenset({("cfs-image", "base-files", "/usr/share/common-licenses/Pretend")}), "forgot edge")

    items = [_item("packs/data-time/ok.txt", LICENCE_TEXT), _item("packs/data-time/other.txt", LICENCE_TEXT)]

    accepted, failing = ki.split_by_policy(ki.find_overlaps(items, index, _policy(anywhere)), _policy(anywhere))
    assert len(accepted) == 2 and failing == []

    accepted, failing = ki.split_by_policy(ki.find_overlaps(items, index, _policy(one_path)), _policy(one_path))
    assert [ov.item.kit_path for ov, _e in accepted] == ["packs/data-time/ok.txt"]
    assert [ov.item.kit_path for ov in failing] == ["packs/data-time/other.txt"], "the same bytes at any other kit path fail"

    accepted, failing = ki.split_by_policy(ki.find_overlaps(items, index, _policy(forgot_one)), _policy(forgot_one))
    assert accepted == [] and len(failing) == 2, "an exception must name EVERY base file with these bytes"

    # a different file at an excepted file's image path is never excused by the exception
    path_only = _item("images/cfs-image/rootfs/usr/share/common-licenses/Pretend", b"not the text", image_path="/usr/share/common-licenses/Pretend", component="cfs-image")
    accepted, failing = ki.split_by_policy(ki.find_overlaps([path_only], index, _policy(anywhere)), _policy(anywhere))
    assert accepted == [] and len(failing) == 1


def _marked(name: str, version: str = "1", *, image_ref: str, ctype: str = "library", arch: str = "arm64", digest: str | None = None) -> dict:
    props = [{"name": licences.PROP_OPERATOR_SUPPLIED, "value": "true"}, {"name": sbom.PROP_BASE_IMAGE, "value": image_ref},
             {"name": sbom.PROP_ARCHITECTURE, "value": arch}]
    if digest:
        props.append({"name": sbom.PROP_BASE_IMAGE_DIGEST, "value": digest})
    return {"type": ctype, "name": name, "version": version, "licenses": [{"license": {"id": "GPL-3.0-only"}}], "properties": props}


def test_the_operator_supplied_marker_is_tied_to_the_inventory_in_both_directions():
    index = _fake_index()
    ref, digest = "pretend:1@sha256:" + "ab" * 32, "sha256:" + "ab" * 32
    good = {"components": [
        _marked(ref.partition("@")[0], digest, image_ref=ref, ctype="container", digest=digest),
        _marked("grep", "3.7-1build1", image_ref=ref), _marked("libc6", "2.35-0ubuntu3.8", image_ref=ref), _marked("base-files", "12ubuntu4.6", image_ref=ref),
    ]}
    reports, owned = ki.check_operator_supplied({"cfs-image": good}, index)
    assert [r.problems for r in reports] == [[]] and reports[0].marked_components == 4
    assert owned == {("cfs-image", "grep"), ("cfs-image", "libc6"), ("cfs-image", "base-files"), ("cfs-image", ki.UNOWNED)}

    # a marked component with no inventory entry
    ghost = {"components": good["components"] + [_marked("evil-gpl", "1.0", image_ref=ref)]}
    reports, _ = ki.check_operator_supplied({"cfs-image": ghost}, index)
    assert any("evil-gpl" in p and "no entry" in p for p in reports[0].problems), reports[0].problems

    # a marked component of the right name, wrong version
    wrong = {"components": [c if c["name"] != "grep" else _marked("grep", "9.9", image_ref=ref) for c in good["components"]]}
    reports, _ = ki.check_operator_supplied({"cfs-image": wrong}, index)
    assert any("grep" in p and "9.9" in p for p in reports[0].problems)

    # an inventory package the SBOM does not mark (the other direction)
    missing = {"components": [c for c in good["components"] if c["name"] != "libc6"]}
    reports, _ = ki.check_operator_supplied({"cfs-image": missing}, index)
    assert any("libc6" in p and "not marked" in p for p in reports[0].problems)

    # a base image no inventory describes
    stranger = {"components": [_marked("grep", "3.7-1build1", image_ref="other:9@sha256:" + "ee" * 32)]}
    reports, _ = ki.check_operator_supplied({"cfs-image": stranger}, index)
    assert any("no committed inventory" in p for p in reports[0].problems)


def test_files_owned_by_a_marked_component_are_looked_for_anywhere_in_the_kit():
    index, policy = _fake_index(), _policy()
    items = [_item("packs/data-time/innocent.bin", GREP), _item("wheels/x.whl!a/b", LIBC, container="wheels/x.whl", kind="wheel-member")]
