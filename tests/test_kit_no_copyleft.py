def test_the_overlap_policy_is_well_formed_and_every_exception_is_true_of_the_inventories():
    """An exception that names a base file must name one the committed inventories hold, with the
    exception's own sha256: a stale or invented exception is a lie, not a policy."""
    policy = ki.load_overlap_policy()
    index = ki.load_base_index()
    assert policy.accepted, "the policy lists no accepted overlap"
    for sha, what in policy.excluded_hashes.items():
        assert len(sha) == 64 and set(sha) <= set("0123456789abcdef") and what
    assert hashlib.sha256(b"").hexdigest() in policy.excluded_hashes   # the empty file
    assert hashlib.sha256(b"\n").hexdigest() in policy.excluded_hashes
    for exc in policy.accepted:
        assert len(exc.sha256) == 64 and exc.reason and exc.base_files
        for image, package, path in exc.base_files:
            hits = [b for b in index.by_sha.get(exc.sha256, []) if (b.image, b.package, b.path) == (image, package, path)]
            assert hits, f"exception {exc.id} names {image}:{package}:{path}, which the inventory does not hold with sha256 {exc.sha256}"
        # ... and the exception names EVERY base file with these bytes (else the proof would fail on one it forgot).
        named = {(b.image, b.package, b.path) for b in index.by_sha[exc.sha256]}
        assert named == set(exc.base_files), f"{exc.id}: base files with these bytes {sorted(named)} != the ones named {sorted(exc.base_files)}"


