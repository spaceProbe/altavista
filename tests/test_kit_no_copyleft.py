def _fast_kit(tmp_path: Path) -> Path:
    kit = tmp_path / "kit"
    build_kit.build(repo_root=REPO_ROOT, out=kit, site=REPO_ROOT / build_kit.DEFAULT_SITE)
    return kit


def _rewrite_kit_manifest(kit: Path, edit) -> None:
    """Applies `edit(doc)` to `KIT_MANIFEST` and rewrites it with every file hash recomputed, so the kit
    still verifies (what someone who can change the kit can always produce: consistency is not authenticity)."""
    doc = json.loads((kit / "KIT_MANIFEST").read_text(encoding="utf-8"))
    edit(doc)
    fresh = kmanifest.build_manifest(
        kit_root=kit, git_commit=doc["git_commit"], git_dirty=doc["git_dirty"], git_status=doc["git_status"],
        images=doc["images"], sboms=doc["sboms"], packs=doc["packs"], vendor=doc["vendor"], wheels=doc["wheels"],
        binaries=doc["binaries"], runs=doc["runs"], gaps=doc["gaps"], operator_supplied_declared=doc["operator_supplied_declared"],
    )
    (kit / "KIT_MANIFEST").unlink()
    kmanifest.write_manifest(fresh, kit)
    assert kmanifest.verify_manifest(kit) == []


