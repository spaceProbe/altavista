"""Question 250(a), task 7: the proof that the kit carries no copyleft from a base image.

Two proofs, both run by `scripts/kit/kit_inventory.py` (read its top doc first):

1. **No file from a base-image package is in the kit.** Every file the kit carries (every
   `KIT_MANIFEST.files` entry, every pack symlink, the image application layers file by file, the members of
   every wheel, of the carried `.deb` and of the vendored static libraries) is compared, by image path and by
   sha256, with every file of both base images (the committed `services/*/BASE_IMAGE_INVENTORY.json`:
   packaged and unowned files). The operator-supplied marker is proven true: each marked SBOM component is
   tied to its inventory entry (and each inventory package to a marked component), and none of the files
   those components own is in the kit. What may overlap is `scripts/kit/base_overlap_exceptions.json`, also
   read by `tests/test_kit_zero_egress_install.py`.
2. **The copyleft scan.** Every SBOM component licence matching GPL, LGPL, AGPL, MPL, EPL, CDDL, EUPL, SSPL
   or BUSL is operator-supplied or on `scripts/kit/copyleft_accepted.json` with its reason; no wheel the kit
   carries bundles a GPL-family library.

Ungated (no docker, no network): the committed records and policy, the logic over a hand-made base
inventory and a fast kit built in the test, and the whole proof over that fast kit with the image SBOMs
regenerated by `scripts/kit/sbom.py`. Gated (`AV_KIT_WITH_IMAGES=1`, the real proof kit
`out/kit/proof`, see `tests/test_kit_zero_egress_install.py`'s "Gating"): the same proof over the kit the
zero-egress install consumes, printing the inventory, and the perturbations with real bytes (`/bin/grep`
and `libc.so.6` read out of the pinned Ubuntu base with `docker run --network none` under the docker lock):
each must fail naming the base package. `AV_KIT_EXTRA_SBOM_DIR` adds a directory of SBOMs (for example the
full set regenerated with `scripts/kit/sbom.py --out DIR`) to the gated run's scan.
"""
