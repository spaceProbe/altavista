def _sbom_doc(*components: dict) -> dict:
    return {"components": list(components)}


def _lib(name: str, licence: str, *, marked: bool = False) -> dict:
    c = {"type": "library", "name": name, "version": "1.0", "licenses": [{"license": {"id": licence}}]}
    if marked:
        c["properties"] = [{"name": licences.PROP_OPERATOR_SUPPLIED, "value": "true"}]
    return c


def test_the_copyleft_scan_fails_an_unmarked_copyleft_component_and_names_it():
    accepted = [ki.AcceptedCopyleft("certifi", "MPL-2.0", "sbom-component", "weak copyleft, unmodified")]
    doc = _sbom_doc(_lib("fine", "MIT"), _lib("certifi", "MPL-2.0"), _lib("grep", "GPL-3.0-only", marked=True), _lib("evil-gpl-lib", "GPL-3.0-only"),
                    _lib("evil-mpl", "MPL-2.0"), _lib("evil-lgpl", "LGPL-2.1-or-later"))
    res = ki.scan_copyleft_sbom("scratch", doc, accepted)
    assert [(c, l) for c, l, _r in res.accepted_used] == [("certifi", "MPL-2.0")]
    assert res.operator_supplied_reported == [("grep", "GPL-3.0-only")]
    failed = " | ".join(res.failures)
    assert "evil-gpl-lib" in failed and "evil-mpl" in failed and "evil-lgpl" in failed
    assert "grep" not in failed and "certifi" not in failed and "fine" not in failed
    # Removing the marker moves a component from reported to failing (what licences.evaluate_sbom_components does too).
    unmarked = ki.scan_copyleft_sbom("scratch", _sbom_doc(_lib("grep", "GPL-3.0-only")), accepted)
    assert len(unmarked.failures) == 1 and "grep" in unmarked.failures[0]
    # An accepted entry is keyed by name AND licence: certifi under a GPL licence is not excused.
    assert ki.scan_copyleft_sbom("scratch", _sbom_doc(_lib("certifi", "GPL-3.0-only")), accepted).failures


def _wheel_doc(carried_libs: list[dict], operator_wheel: dict | None = None, files: list[dict] | None = None) -> dict:
    return {
        "wheels": {"fetched": [{"filename": "numpy-2.5.3.whl", "name": "numpy", "version": "2.5.3", "bundled_libraries": carried_libs, "extension_modules": []}],
                   "operator_supplied": [operator_wheel] if operator_wheel else []},
        "files": files or [],
    }


def test_the_wheel_inventory_scan_fails_a_carried_gpl_family_library():
    gpl = {"library": "libgfortran", "path": "numpy.libs/libgfortran.so.5", "spdx": "GPL-3.0-or-later WITH GCC-exception-3.1", "gpl_family": True}
    blas = {"library": "libscipy_openblas64_", "path": "numpy.libs/libopenblas.so", "spdx": "BSD-3-Clause AND BSD-3-Clause-Open-MPI", "gpl_family": False}
    assert ki.scan_wheel_inventory(_wheel_doc([blas]), []).failures == []
    bad = ki.scan_wheel_inventory(_wheel_doc([blas, gpl]), [])
    assert len(bad.failures) == 1 and "libgfortran" in bad.failures[0]
    # a library whose licence is copyleft but not GPL-family is a finding too (MPL), unless accepted by name
    mpl = {"library": "libmpl", "path": "x.libs/libmpl.so", "spdx": "MPL-2.0", "gpl_family": False}
    assert ki.scan_wheel_inventory(_wheel_doc([mpl]), []).failures
    ok = ki.scan_wheel_inventory(_wheel_doc([mpl]), [ki.AcceptedCopyleft("libmpl", "MPL-2.0", "bundled-library", "reason")])
    assert ok.failures == [] and ok.accepted_used[0][0] == "libmpl"
    # the operator-supplied wheel is listed, and the kit must not carry it
    op = {"filename": "numpy-2.5.3-op.whl", "sha256": "ff" * 32, "gpl_family_libraries": ["libgfortran"]}
    assert ki.scan_wheel_inventory(_wheel_doc([blas], op), []).failures == []
    carried = ki.scan_wheel_inventory(_wheel_doc([blas], op, files=[{"path": "wheels/numpy-2.5.3-op.whl", "sha256": "ff" * 32}]), [])
    assert carried.failures and "numpy-2.5.3-op.whl" in carried.failures[0]


