def _docker_bytes(reference: str, path: str) -> bytes:
    """The bytes of `path` in the pinned base image: `docker run --rm --pull never --network none`, under the docker lock."""
    from altavista.docker_test_lock import lock_docker_tests
    with lock_docker_tests():
        got = subprocess.run(
            ["docker", "run", "--rm", "--pull", "never", "--network", "none", "--label", "av.test=1",
             "--label", f"av.nocopyleft={uuid.uuid4().hex[:12]}", "--entrypoint", "cat", reference, path],
            capture_output=True, timeout=120)
    assert got.returncode == 0, got.stderr.decode(errors="replace")
    return got.stdout


def _hardlink_copy(src: Path, dst: Path) -> None:
    def link_or_copy(a: str, b: str) -> None:
        try:
            os.link(a, b)
        except OSError:
            shutil.copy2(a, b)
    shutil.copytree(src, dst, symlinks=True, copy_function=link_or_copy)


def _replace_file(path: Path, data: bytes) -> None:
    mode = path.stat().st_mode & 0o7777
    path.unlink()   # never write through a hard link shared with the proof kit
    path.write_bytes(data)
    path.chmod(mode)


